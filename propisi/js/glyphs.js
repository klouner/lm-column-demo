/* ---------- Разбор путей ---------- */
function flatten(d) {
  const t = d.match(/[MLC]|-?\d*\.?\d+/g);
  const pts = [];
  let i = 0, cx = 0, cy = 0, cmd = '';
  const num = () => parseFloat(t[i++]);
  while (i < t.length) {
    if (/[MLC]/.test(t[i])) cmd = t[i++];
    if (cmd === 'M' || cmd === 'L') { cx = num(); cy = num(); pts.push([cx, cy]); if (cmd === 'M') cmd = 'L'; }
    else {
      const x1 = num(), y1 = num(), x2 = num(), y2 = num(), x = num(), y = num();
      for (let k = 1; k <= 24; k++) {
        const s = k / 24, r = 1 - s;
        pts.push([r * r * r * cx + 3 * r * r * s * x1 + 3 * r * s * s * x2 + s * s * s * x,
                  r * r * r * cy + 3 * r * r * s * y1 + 3 * r * s * s * y2 + s * s * s * y]);
      }
      cx = x; cy = y;
    }
  }
  return pts;
}

// Равномерная расстановка точек вдоль ломаной
export function resample(pts, step) {
  if (pts.length < 2) return pts.slice();
  const out = [pts[0]];
  let acc = 0;
  for (let i = 1; i < pts.length; i++) {
    let [ax, ay] = pts[i - 1]; const [bx, by] = pts[i];
    let seg = Math.hypot(bx - ax, by - ay);
    while (acc + seg >= step) {
      const f = (step - acc) / seg;
      ax += (bx - ax) * f; ay += (by - ay) * f;
      out.push([ax, ay]);
      seg = Math.hypot(bx - ax, by - ay); acc = 0;
    }
    acc += seg;
  }
  const l = pts[pts.length - 1], o = out[out.length - 1];
  if (Math.hypot(l[0] - o[0], l[1] - o[1]) > step * 0.3) out.push(l);
  return out;
}

function build(def, tf, slant) {
  const meta = typeof def[def.length - 1] === 'object' ? def[def.length - 1] : {};
  const paths = def.slice(1).filter(s => typeof s === 'string');
  let strokes = paths.map(flatten);
  if (tf) strokes = strokes.map(s => s.map(tf));
  let w = def[0];
  if (tf) w = tf([w, 100])[0];
  if (slant) strokes = strokes.map(s => s.map(([x, y]) => [x + (100 - y) * SLANT, y]));
  strokes = strokes.map(s => resample(s, 1.5));
  const xi = meta.x ?? strokes.length - 1;
  const last = strokes[xi];
  let entry = strokes[0][0];
  if (meta.a) { const [ax, ay] = tf ? tf(meta.a) : meta.a; entry = [ax + (100 - ay) * SLANT, ay]; }
  return { w, strokes, entry, exit: last[last.length - 1], join: meta.j !== 0 };
}

const cache = new Map();
const isUpper = ch => ch !== ch.toLowerCase();

/** set: 'p' — печатные, 'c' — прописные, 'e' — элементы без наклона, 'ce' — элементы с наклоном */
export function getGlyph(set, key) {
  const id = set + key;
  if (cache.has(id)) return cache.get(id);
  let g = null;
  if (ELEMENTS[key] && (set === 'e' || set === 'ce' || !/[а-яёА-ЯЁ]/.test(key))) {
    g = build(ELEMENTS[key], null, set === 'c' || set === 'ce');
  } else if (set === 'p') {
    if (PU[key]) g = build(PU[key]);
    else if (PL_CUSTOM[key]) g = build(PL_CUSTOM[key]);
    else if (PU[key.toUpperCase()]) g = build(PU[key.toUpperCase()], ([x, y]) => [x * 0.6, 50 + y * 0.5]);
  } else if (set === 'c') {
    if (isUpper(key)) {
      if (CU_CUSTOM[key]) g = build(CU_CUSTOM[key], null, true);
      else if (CL[key.toLowerCase()]) g = build(CL[key.toLowerCase()], ([x, y]) => [x * 1.4, (y - 50) * 2], true);
    } else if (CL[key]) g = build(CL[key], null, true);
  }
  cache.set(id, g);
  return g;
}

/** Раскладка слова/набора знаков: возвращает штрихи в единицах (x от 0) и общую ширину */
export function layout(set, keys) {
  const strokes = [];
  let x = 0, prev = null, prevX = 0, minX = Infinity, maxX = -Infinity;
  const gap = set === 'p' ? 14 : set === 'c' ? 2 : 16;
  for (const key of keys) {
    if (key === ' ') { x += set === 'p' ? 44 : 34; prev = null; continue; }
    const g = getGlyph(set, key);
    if (!g) continue;
    const punct = !/[а-яёА-ЯЁ]/.test(key) && set !== 'e' && set !== 'ce';
    if (punct && set === 'c') x += 4;
    if (set === 'c' && prev && prev.join && !punct && !isUpper(key)) {
      const [ax, ay] = [prev.exit[0] + prevX, prev.exit[1]], [bx, by] = [g.entry[0] + x, g.entry[1]];
      const dx = bx - ax, dy = by - ay;
      if (Math.hypot(dx, dy) > 3) {
        const c = [];
        for (let k = 0; k <= 12; k++) {
          const s = k / 12, r = 1 - s;
          const x1 = ax + dx * 0.45, y1 = ay + dy * 0.25, x2 = bx - dx * 0.2, y2 = by - dy * 0.35;
          c.push([r * r * r * ax + 3 * r * r * s * x1 + 3 * r * s * s * x2 + s * s * s * bx,
                  r * r * r * ay + 3 * r * r * s * y1 + 3 * r * s * s * y2 + s * s * s * by]);
        }
        // соединение приклеиваем к предыдущему штриху, чтобы вести линию не отрывая руки
        const target = strokes[prev._idx];
        target.push(...resample(c, 1.5).slice(1));
      }
    }
    const base = strokes.length;
    for (const s of g.strokes) {
      const moved = s.map(([px, py]) => [px + x, py]);
      for (const p of moved) { if (p[0] < minX) minX = p[0]; if (p[0] > maxX) maxX = p[0]; }
      strokes.push(moved);
    }
    const xi = g.strokes.indexOf(g.strokes.find(s => s[s.length - 1] === g.exit));
    prev = { ...g, _idx: base + (xi < 0 ? g.strokes.length - 1 : xi) };
    prevX = x;
    x += g.w + gap;
  }
  if (!strokes.length) return { strokes, w: 0 };
  // сдвигаем так, чтобы слева не было пустоты
  for (const s of strokes) for (const p of s) p[0] -= minX;
  return { strokes, w: maxX - minX };
}

